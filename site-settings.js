// RMO ÉLAN — Shared International Settings

const RMO_SETTINGS = {
  currency: localStorage.getItem("rmoCurrency") || "NGN",
  language: localStorage.getItem("rmoLanguage") || "en",
  rates: {},
  ratesLoaded: false
};

function getRmoCurrency() {
  return RMO_SETTINGS.currency;
}

function getRmoLanguage() {
  return RMO_SETTINGS.language;
}

function setRmoCurrency(currency) {
  if (!RMO_SETTINGS.rates[currency]) return;

  RMO_SETTINGS.currency = currency;
  localStorage.setItem("rmoCurrency", currency);
  window.dispatchEvent(new Event("rmoCurrencyChanged"));
}

function setRmoLanguage(language) {
  RMO_SETTINGS.language = language;
  localStorage.setItem("rmoLanguage", language);

  translateRmoPage();
  window.dispatchEvent(new Event("rmoLanguageChanged"));
}

document.documentElement.lang = getRmoLanguage();
document.documentElement.dir =
  getRmoLanguage() === "ar" ? "rtl" : "ltr";

function convertRmoPrice(amountInNaira) {
  const rate = RMO_SETTINGS.rates[getRmoCurrency()];

  if (!rate || !Number.isFinite(Number(amountInNaira))) {
    return null;
  }

  return Number(amountInNaira) * rate;
}

function formatRmoPrice(amountInNaira) {
  const converted = convertRmoPrice(amountInNaira);

  if (converted === null) return "Price unavailable";

  return new Intl.NumberFormat(undefined, {
    style: "currency",
    currency: getRmoCurrency()
  }).format(converted);
}

function createRmoSelectors() {
  const header = document.querySelector("header");
  if (!header) return;

  let preferences = document.querySelector(".rmo-preferences");

  if (!preferences) {
    preferences = document.createElement("div");
    preferences.className = "rmo-preferences";
    header.appendChild(preferences);
  }

  let currencySelector = document.getElementById("rmoCurrencySelector");

  if (!currencySelector) {
    const currencyLabel = document.createElement("label");
    currencyLabel.htmlFor = "rmoCurrencySelector";
    currencyLabel.textContent = "Currency";

    currencySelector = document.createElement("select");
    currencySelector.id = "rmoCurrencySelector";

    currencySelector.addEventListener("change", function() {
      setRmoCurrency(this.value);
    });

    preferences.append(currencyLabel, currencySelector);
  }

  currencySelector.replaceChildren();

  const currencyNames = new Intl.DisplayNames(["en"], {
    type: "currency"
  });

  Object.keys(RMO_SETTINGS.rates).sort().forEach(code => {
    const option = document.createElement("option");
    option.value = code;

    try {
      option.textContent = `${currencyNames.of(code)} (${code})`;
    } catch (error) {
      option.textContent = code;
    }

    currencySelector.appendChild(option);
  });

  if (!RMO_SETTINGS.rates[getRmoCurrency()]) {
    RMO_SETTINGS.currency = "NGN";
    localStorage.setItem("rmoCurrency", "NGN");
  }

  currencySelector.value = getRmoCurrency();

  let languageSelector = document.getElementById("rmoLanguageSelector");

  if (!languageSelector) {
    const languageLabel = document.createElement("label");
    languageLabel.htmlFor = "rmoLanguageSelector";
    languageLabel.textContent = "Language";

    languageSelector = document.createElement("select");
    languageSelector.id = "rmoLanguageSelector";

    const languages = [
      ["en", "English"],
      ["fr", "Français"],
      ["es", "Español"],
      ["pt", "Português"],
      ["ar", "العربية"],
      ["de", "Deutsch"],
      ["zh", "中文"],
      ["ja", "日本語"],
      ["it", "Italiano"],
      ["sw", "Kiswahili"],
      ["nl", "Nederlands"],
      ["tr", "Türkçe"],
      ["hi", "हिन्दी"],
      ["ko", "한국어"]
    ];

    languages.forEach(([code, name]) => {
      const option = document.createElement("option");
      option.value = code;
      option.textContent = name;
      languageSelector.appendChild(option);
    });

    languageSelector.addEventListener("change", function() {
      setRmoLanguage(this.value);
    });

    preferences.append(languageLabel, languageSelector);
  }

  languageSelector.value = getRmoLanguage();

  if (!document.getElementById("rmoPreferencesStyle")) {
    const style = document.createElement("style");
    style.id = "rmoPreferencesStyle";
    style.textContent = `
      header {
        flex-wrap: wrap;
        gap: 15px;
      }

      .rmo-preferences {
        display: flex;
        align-items: center;
        gap: 8px;
        margin-left: auto;
        font: 12px Arial, sans-serif;
      }

      .rmo-preferences select {
        padding: 9px;
        border: 1px solid #cfc3ba;
        background: white;
        color: #241d1d;
        max-width: 190px;
      }

      @media(max-width: 650px) {
        .rmo-preferences {
          margin: 0 auto;
          flex-wrap: wrap;
        }
      }
    `;

    document.head.appendChild(style);
  }
}

window.addEventListener("rmoCurrencyChanged", function() {
  const selector = document.getElementById("rmoCurrencySelector");
  if (selector) selector.value = getRmoCurrency();
});

async function loadRmoRates() {
  try {
    const response = await fetch(
      "https://open.er-api.com/v6/latest/NGN"
    );

    if (!response.ok) throw new Error("Exchange-rate service unavailable.");

    const data = await response.json();

    if (data.result !== "success" || !data.rates) {
      throw new Error("Exchange rates could not be loaded.");
    }

    RMO_SETTINGS.rates = data.rates;
    RMO_SETTINGS.ratesLoaded = true;

    createRmoSelectors();
    window.dispatchEvent(new Event("rmoRatesLoaded"));

  } catch (error) {
    console.error("RMO ÉLAN currency error:", error);
  }
}

function translateRmoPage() {
  if (typeof RMO_TRANSLATIONS === "undefined") return;

  const language = getRmoLanguage();
  const translations = RMO_TRANSLATIONS[language] || {};
  const fallback = RMO_TRANSLATIONS.en || {};

  document.querySelectorAll("[data-translate], [data-translate-placeholder]").forEach(element => {
    const key = element.getAttribute("data-translate");

    if (key) {
      const translatedText = translations[key] || fallback[key];
      if (translatedText) element.textContent = translatedText;
    }

    const placeholderKey = element.getAttribute("data-translate-placeholder");
    if (placeholderKey) {
      const translatedPlaceholder = translations[placeholderKey] || fallback[placeholderKey];
      if (translatedPlaceholder) element.placeholder = translatedPlaceholder;
    }
  });

  document.documentElement.lang = language;
  document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
}

