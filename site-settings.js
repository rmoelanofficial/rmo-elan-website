const RMO_SETTINGS = {
  currency: localStorage.getItem("rmoCurrency") || "NGN",
  language: localStorage.getItem("rmoLanguage") || "en",
  rates: {},
  ratesLoaded: false
};

function getRmoCurrency() {
  return RMO_SETTINGS.currency;
}

function getRmoLanguage() {
  return RMO_SETTINGS.language;
}

function setRmoCurrency(currency) {
  if (!RMO_SETTINGS.rates[currency]) return;

  RMO_SETTINGS.currency = currency;
  localStorage.setItem("rmoCurrency", currency);
  window.dispatchEvent(new Event("rmoCurrencyChanged"));
}

function setRmoLanguage(language) {
  RMO_SETTINGS.language = language;
  localStorage.setItem("rmoLanguage", language);

  translateRmoPage();
  window.dispatchEvent(new Event("rmoLanguageChanged"));
}

document.documentElement.lang = getRmoLanguage();
document.documentElement.dir =
  getRmoLanguage() === "ar" ? "rtl" : "ltr";

function convertRmoPrice(amountInNaira) {
  const rate = RMO_SETTINGS.rates[getRmoCurrency()];

  if (!rate || !Number.isFinite(Number(amountInNaira))) {
    return null;
  }

  return Number(amountInNaira) * rate;
}

function formatRmoPrice(amountInNaira) {
  const converted = convertRmoPrice(amountInNaira);

  if (converted === null) return "Price unavailable";

  return new Intl.NumberFormat(undefined, {
    style: "currency",
    currency: getRmoCurrency()
  }).format(converted);
}

